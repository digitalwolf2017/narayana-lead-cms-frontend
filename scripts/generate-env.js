/**
 * Synchronizes variables from root .env file into Angular environment files:
 * - src/environments/environment.ts (Production)
 * - src/environments/environment.development.ts (Development)
 */
const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const envPath = path.join(rootDir, '.env');
const environmentsDir = path.join(rootDir, 'src', 'environments');

// Parse .env file if present
const parsedEnv = {};
if (fs.existsSync(envPath)) {
  const content = fs.readFileSync(envPath, 'utf-8');
  content.split('\n').forEach((line) => {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) return;
    const match = trimmed.match(/^([^=]+)=(.*)$/);
    if (match) {
      const key = match[1].trim();
      let val = match[2].trim();
      // Remove surrounding quotes if present
      if (
        (val.startsWith('"') && val.endsWith('"')) ||
        (val.startsWith("'") && val.endsWith("'"))
      ) {
        val = val.slice(1, -1);
      }
      parsedEnv[key] = val;
    }
  });
}

function getEnv(key, defaultValue = '') {
  return process.env[key] || parsedEnv[key] || defaultValue;
}

const apiBaseUrl = getEnv('API_BASE_URL', '/api/v1/backend');
const tokenStorageKey = getEnv('TOKEN_STORAGE_KEY', 'auth_token');
const publicWebBaseUrl = getEnv('PUBLIC_WEB_BASE_URL', 'https://wbnarayanaschools.in');
const previewBaseUrl = getEnv('PREVIEW_BASE_URL', 'http://localhost:3000');
const mediaCdnBaseUrl = getEnv('MEDIA_CDN_BASE_URL', 'https://apiframework.wbnarayanaschools.in');

if (!fs.existsSync(environmentsDir)) {
  fs.mkdirSync(environmentsDir, { recursive: true });
}

const prodEnvContent = `// Auto-generated by scripts/generate-env.js from .env
// Edit .env and re-run "npm run env" to update.

export const environment = {
  production: true,
  apiBaseUrl: '${apiBaseUrl}',
  tokenStorageKey: '${tokenStorageKey}',
  publicWebBaseUrl: '${publicWebBaseUrl}',
  previewBaseUrl: '${previewBaseUrl}',
  mediaCdnBaseUrl: '${mediaCdnBaseUrl}',
};
`;

const devEnvContent = `// Auto-generated by scripts/generate-env.js from .env
// Edit .env and re-run "npm run env" to update.

export const environment = {
  production: false,
  apiBaseUrl: '${apiBaseUrl}',
  tokenStorageKey: '${tokenStorageKey}',
  publicWebBaseUrl: '${publicWebBaseUrl}',
  previewBaseUrl: '${previewBaseUrl}',
  mediaCdnBaseUrl: '${mediaCdnBaseUrl}',
};
`;

fs.writeFileSync(path.join(environmentsDir, 'environment.ts'), prodEnvContent, 'utf-8');
fs.writeFileSync(path.join(environmentsDir, 'environment.development.ts'), devEnvContent, 'utf-8');

console.log('✓ Successfully synchronized Angular environments from .env:');
console.log(`  - API_BASE_URL: ${apiBaseUrl}`);
console.log(`  - TOKEN_STORAGE_KEY: ${tokenStorageKey}`);
console.log(`  - PUBLIC_WEB_BASE_URL: ${publicWebBaseUrl}`);
console.log(`  - PREVIEW_BASE_URL: ${previewBaseUrl}`);
console.log(`  - MEDIA_CDN_BASE_URL: ${mediaCdnBaseUrl}`);
